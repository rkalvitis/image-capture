#!/usr/bin/env python3
"""Hybrid background mask: model union minus geometric rod/mount carve-out.

The two experiments fail in opposite ways: BiRefNet (masks/birefnet) captures
the whole beetle but cannot know the mounting rod and hub are background;
SAM+geometry (masks/sam_geom) excludes the rod but sometimes drops parts of
the dark body. This script combines them:

  1. evidence = union of the two masks (covers either model's misses)
  2. carve away what the rig geometry PROVES is mount, projected through the
     calibrated camera: a capsule corridor along the rod axis (specimen →
     hub) and a disk over the hub, both shifted by the same sharpness-refined
     offset used in experiment 2 and skipped where they are occluded by the
     beetle (hidden mount can't appear in the image)
  3. keep the connected component at the refined specimen point

Residual limitation: the few px where the pin enters the body are inherently
ambiguous — the carve-out keeps a protected zone around the body so legs
aren't amputated, and the pin stub inside that zone survives.

    pixi run -e masking mask-hybrid -- datasets/phone_<ts> [--limit N]

Writes masks/hybrid/stack_<n>.png (+ preview/), masks/hybrid_report.html.
"""

import argparse
import html
import os
import sys

import numpy as np
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from compare_masks import CSS, C_A, C_B, b64_jpeg, hex_rgb
from mask_common import find_stacks, load_image, load_mask, overlay_preview, \
    save_mask
from mask_sam_geom import camera_basis, keep_component_at, project, \
    sharpness_recenter
from plot_stacks import fit_geometry, load, rotm


def build_report(session, rows, out_html):
    ious_a = [r['iou_a'] for r in rows]
    ious_b = [r['iou_b'] for r in rows]
    parts = [
        '<title>Beetle-Only Masks</title>',
        f'<style>{CSS}</style>',
        '<header><h1>Beetle-Only Masks</h1>',
        f'<p class="sub">Hybrid masks for {html.escape(session)}: union of '
        'the two experiments with the rod corridor and mount hub carved out '
        'by the rig geometry. The removal panel tints what the carve-out '
        'and component filter dropped from the model union.</p>',
        '<div class="methods">'
        f'<span><i class="dot" style="background:{C_B}"></i>hybrid mask'
        '</span>'
        f'<span><i class="dot" style="background:{C_A}"></i>removed '
        '(union − hybrid)</span></div>',
        '<div class="stats">'
        f'<div class="stat"><b class="mono">{np.mean(ious_a):.3f}</b>'
        '<span>mean IoU vs BiRefNet</span></div>'
        f'<div class="stat"><b class="mono">{np.mean(ious_b):.3f}</b>'
        '<span>mean IoU vs SAM+geom</span></div>'
        f'<div class="stat"><b class="mono">'
        f'{np.mean([r["removed_pct"] for r in rows]):.1f}%</b>'
        '<span>mean of union removed</span></div>'
        '</div></header><main>',
    ]
    for r in rows:
        parts.append(
            f'<section class="row"><div class="rowhead">'
            f'<span class="id">Stack {r["stack"]}</span>'
            f'<span class="m">area <b class="mono">{r["area_pct"]:.2f}%'
            '</b></span>'
            f'<span class="m">IoU vs A <b class="mono">{r["iou_a"]:.3f}</b>'
            f' · vs B <b class="mono">{r["iou_b"]:.3f}</b></span>'
            f'<span class="m">removed <b class="mono">'
            f'{r["removed_pct"]:.1f}%</b> of union</span>'
            f'</div><div class="imgs">' +
            ''.join(f'<figure><img loading="lazy" alt="{cap}" '
                    f'src="data:image/jpeg;base64,{b64}">'
                    f'<figcaption>{cap}</figcaption></figure>'
                    for cap, b64 in zip(
                        ('composite', 'hybrid', 'removed'), r['panels'])) +
            '</div></section>')
    parts.append('</main><footer>Generated by scripts/mask_hybrid.py · '
                 'hybrid = (BiRefNet ∪ SAM+geometry) − projected rod '
                 'corridor − hub disk, connected component at the specimen.'
                 '</footer>')
    with open(out_html, 'w') as f:
        f.write('\n'.join(parts))


def main():
    ap_ = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap_.add_argument('session')
    ap_.add_argument('--a', default='masks/birefnet')
    ap_.add_argument('--b', default='masks/sam_geom')
    ap_.add_argument('--intrinsics', default='calibration/intrinsics.yaml')
    ap_.add_argument('--working-distance', type=float, default=25.0)
    ap_.add_argument('--object-radius-mm', type=float, default=8.0)
    ap_.add_argument('--roll', type=float, default=270.0,
                     choices=(0.0, 90.0, 180.0, 270.0))
    ap_.add_argument('--orient', choices=('cw', 'ccw'), default='cw')
    ap_.add_argument('--rod-radius-mm', type=float, default=2.5,
                     help='carve-out corridor radius around the rod axis '
                          '(default 2.5)')
    ap_.add_argument('--rod-span-mm', default='5,130',
                     help='rod carve-out span below the specimen '
                          '(default 5,130)')
    ap_.add_argument('--hub-mm', default='45,100',
                     help='"radius,depth" of the hub carve-out disk '
                          '(default 45,100)')
    ap_.add_argument('--keep-radius', type=float, default=0.8,
                     help='protected zone around the refined centre, as a '
                          'fraction of the prompt-box half-size (default 0.8)')
    ap_.add_argument('--stacks-per-block', type=int, default=8)
    ap_.add_argument('--limit', type=int, default=None)
    ap_.add_argument('--out', default='masks/hybrid',
                     help='output dir under the session (default '
                          'masks/hybrid); the report lands next to it as '
                          '<out>_report.html')
    args = ap_.parse_args()

    import cv2
    session = args.session.rstrip('/')
    out_dir = os.path.join(session, args.out)
    stacks = load(session)
    spb = args.stacks_per_block
    ap, ad, spec, o_b, _ = fit_geometry(stacks, spb)
    wd = args.working_distance * 1e-3
    pose1 = [s for s in stacks if (s['n'] - 1) % spb == 0]
    t_b = np.mean([rotm(s['rel_q']).T @ (spec + wd * ad - s['rel'])
                   for s in pose1], axis=0)
    with open(args.intrinsics) as f:
        calib = yaml.safe_load(f)
    K = np.array(calib['camera_matrix'])
    size_land = calib['image_size']
    R_bc = camera_basis(o_b, args.roll)

    t0, t1 = (float(v) * 1e-3 for v in args.rod_span_mm.split(','))
    hub_r, hub_d = (float(v) * 1e-3 for v in args.hub_mm.split(','))
    by_n = {s['n']: s for s in stacks}
    composites = find_stacks(session)
    if args.limit:
        composites = composites[:args.limit]

    rows = []
    for n, path in composites:
        pa = os.path.join(session, args.a, f'stack_{n:02d}.png')
        pb = os.path.join(session, args.b, f'stack_{n:02d}.png')
        if not (os.path.exists(pa) and os.path.exists(pb)):
            print(f'stack {n:2d}: missing input mask, skipped')
            continue
        img, s = load_image(path), by_n[n]
        W, H = img.size
        ma, mb = load_mask(pa) >= 0.5, load_mask(pb) >= 0.5
        union = ma | mb

        pos, z = project(spec, s, R_bc, t_b, K, size_land, args.orient)
        half = K[0, 0] * args.object_radius_mm * 1e-3 / z * 1.1
        raw_pos = pos
        pos = sharpness_recenter(img, pos, half)
        shift = np.array(pos) - np.array(raw_pos)
        keep_r = args.keep_radius * half

        R_ob = rotm(s['rel_q'])
        lens = s['rel'] + R_ob @ t_b
        spec_c = R_bc @ (R_ob.T @ (spec - lens))

        def visible(P):
            """Projected px of P (with the refined shift), or None if the
            point is behind the camera or occluded by the beetle. Also
            says whether P sits IN FRONT of the beetle (closer to the
            camera), in which case it occludes the beetle and may be
            carved even inside the protected zone."""
            pc = R_bc @ (R_ob.T @ (P - lens))
            if pc[2] <= 1e-4:
                return None, None, False
            u = pc / np.linalg.norm(pc)
            behind = np.linalg.norm(pc) > np.linalg.norm(spec_c)
            if np.linalg.norm(np.cross(spec_c, u)) < 6e-3 and behind:
                return None, None, False
            p, zz = project(P, s, R_bc, t_b, K, size_land, args.orient)
            if p is None:
                return None, None, False
            in_front = np.linalg.norm(pc) < np.linalg.norm(spec_c) - 3e-3
            return (p[0] + shift[0], p[1] + shift[1]), zz, in_front

        # two carve layers: `outer` never cuts inside the protected zone
        # (a hidden rod there would slice the beetle); `inner` is a slim
        # corridor for rod points PROVABLY in front of the beetle — those
        # occlude it, so cutting them inside the zone is correct
        outer = np.zeros((H, W), dtype=np.uint8)
        inner = np.zeros((H, W), dtype=np.uint8)
        for t in np.linspace(t0, t1, 48):
            p, zz, in_front = visible(spec - t * ad)
            if p is None:
                continue
            r_px = max(4, int(K[0, 0] * args.rod_radius_mm * 1e-3 / zz))
            cv2.circle(outer, (int(p[0]), int(p[1])), r_px, 1, -1)
            if in_front:
                r_in = max(3, int(K[0, 0] * 0.6 * args.rod_radius_mm
                                  * 1e-3 / zz))
                cv2.circle(inner, (int(p[0]), int(p[1])), r_in, 1, -1)
        p, zz, _ = visible(spec - hub_d * ad)
        if p is not None:
            r_px = int(K[0, 0] * hub_r / zz)
            cv2.circle(outer, (int(p[0]), int(p[1])), r_px, 1, -1)
        # the protected zone is absolute for the outer layer: a circle
        # whose CENTRE is outside may still reach in with its radius
        cv2.circle(outer, (int(pos[0]), int(pos[1])), int(keep_r), 0, -1)
        carve = outer | inner

        kept = union & ~carve.astype(bool)
        kept = keep_component_at(kept.astype(np.uint8), pos)
        m = kept.astype(np.float32)

        save_mask(m, os.path.join(out_dir, f'stack_{n:02d}.png'))
        overlay_preview(img, m, os.path.join(out_dir, 'preview',
                                             f'{n:02d}.jpg'))

        inter_a, inter_b = (m.astype(bool) & ma).sum(), \
            (m.astype(bool) & mb).sum()
        iou_a = inter_a / (m.astype(bool) | ma).sum()
        iou_b = inter_b / (m.astype(bool) | mb).sum()
        removed = union.sum() - m.sum()
        removed_pct = 100 * removed / union.sum() if union.sum() else 0.0

        # report panels: composite · hybrid overlay · removed map
        sc = 440 / max(img.size)
        small = np.asarray(img.resize((round(W * sc), round(H * sc)))) \
            .astype(np.float32)
        mk = cv2.resize(m, (small.shape[1], small.shape[0])) >= 0.5
        un = cv2.resize(union.astype(np.uint8),
                        (small.shape[1], small.shape[0])) > 0
        ov = small * (0.22 + 0.78 * mk[..., None])
        cont, _ = cv2.findContours(mk.astype(np.uint8), cv2.RETR_LIST,
                                   cv2.CHAIN_APPROX_SIMPLE)
        ov = ov.astype(np.uint8).copy()
        cv2.drawContours(ov, cont, -1,
                         tuple(int(v) for v in hex_rgb(C_B)), 2)
        rem = small * 0.22
        rem[mk] = small[mk]
        rem[un & ~mk] = 0.45 * small[un & ~mk] + 0.55 * hex_rgb(C_A)
        rows.append({'stack': n, 'area_pct': 100 * m.mean(),
                     'iou_a': iou_a, 'iou_b': iou_b,
                     'removed_pct': removed_pct,
                     'panels': [b64_jpeg(small.astype(np.uint8)),
                                b64_jpeg(ov), b64_jpeg(rem.astype(np.uint8))]})
        print(f'stack {n:2d}: area {100 * m.mean():5.2f}%, removed '
              f'{removed_pct:4.1f}% of union, IoU A {iou_a:.3f} B {iou_b:.3f}')

    out_html = out_dir.rstrip('/') + '_report.html'
    build_report(session, rows, out_html)
    print(f'\n→ {out_dir}\n→ {out_html}')


if __name__ == '__main__':
    main()
